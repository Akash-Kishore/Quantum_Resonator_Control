def status(side):
    if side.startswith("ctrl:"):
        return "ok" if any(m == side and c in VAL_CONDS for (m, p, c) in FILEIDX) else "MISSING"
    st = cfg_stats(side)
    return "ok" if (st[2] >= 5 and len(RUNS.get(side, {})) >= 5) else ("INCOMPLETE(val=%d)" % st[2])


