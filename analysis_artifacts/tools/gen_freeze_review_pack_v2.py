VAL_CONDS = ["nom", "ofat_drift_sigma_1000", "ofat_shots_128", "ofat_t2_50"]


def f4(x):
    return "%.4f" % x if isinstance(x, (int, float)) else ("n/a" if x is None else str(x))


def f1d(x):
    return "%.1f" % x if isinstance(x, (int, float)) else "n/a"


# ---------------- data ----------------
con = sqlite3.connect(os.path.join(S, "db", "qstudy.sqlite"))
con.row_factory = sqlite3.Row
DB = [dict(r) for r in con.execute("SELECT * FROM evals")]
con.close()


def file_ok(r):
    npz = r["npz_path"] or ""
    p = npz if os.path.isabs(npz) else os.path.join(S, npz)
    if "_invalid" in p.lower():
        return False
    jp = p[:-4] + ".json" if p.endswith(".npz") else p
    if not os.path.exists(jp):
        return False
    try:
        j = json.load(open(jp, encoding="utf-8"))
    except Exception:
        return False
    return (abs((j.get("lock_w1000_mean") or -1) - (r["lock_w1000_mean"] or -2)) < 1e-9
            and (j.get("episodes") or 0) == (r["episodes"] or 0))


PER = {}
for r in DB:
    if r["split"] != "val" or r["cond_id"] not in VAL_CONDS:
        continue
    m = re.search(r"runs.(.+?).seed_(\d+)$", r["model_dir"] or "")
    if not m or not file_ok(r):
        continue
    PER.setdefault(m.group(1), {}).setdefault(int(m.group(2)), {})[r["cond_id"]] = r["lock_w1000_mean"]


def cfg_stats(cfg):
    per = PER.get(cfg, {})
    use = [statistics.mean(v.values()) for v in per.values() if len(v) == 4]
    sd = statistics.stdev(use) if len(use) > 1 else 0.0
    return (statistics.mean(use) if use else None, sd, len(use))


FILEIDX = {}
for p in glob.glob(os.path.join(S, "results", "val", "*.json")):
    if "_INVALID" in p:
        continue
    try:
        j = json.load(open(p, encoding="utf-8"))
    except Exception:
        continue
    if "method" not in j or "lock_w1000_mean" not in j:
        continue
    probe = (j.get("cfg") or {}).get("probe")
    FILEIDX[(j["method"], probe, j.get("cond_id"))] = j["lock_w1000_mean"]

RUNS = {}
for p in sorted(glob.glob(os.path.join(S, "runs", "*", "seed_*", "train_summary.json"))):
    m = re.match(r"runs[/\\](.+)[/\\]seed_(\d+)[/\\]train_summary.json", os.path.relpath(p, S))
    if m:
        try:
            RUNS.setdefault(m.group(1), {})[int(m.group(2))] = json.load(open(p, encoding="utf-8"))
        except Exception:
            pass

f3 = json.load(open(os.path.join(W, "results", "f3_recompute.json"), encoding="utf-8"))
f5 = json.load(open(os.path.join(W, "results", "f5_oracle_check.json"), encoding="utf-8"))
cfg_audit = json.load(open(os.path.join(W, "results", "audit_eval_cfg_report.json"), encoding="utf-8"))
suite_txt = open(os.path.join(W, "results", "m2_suite_unittests.txt"), errors="replace").read()


def read_any(p):
    """Read text regardless of a UTF-16 BOM (PowerShell `>` redirection writes UTF-16)."""
    raw = open(p, "rb").read()
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return raw.decode("utf-16", errors="replace")
    return raw.decode("utf-8", errors="replace")


audit_filter_txt = read_any(os.path.join(W, "results", "audit_filter_params.txt"))

