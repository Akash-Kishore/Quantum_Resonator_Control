    if slot == "C1_legacy_analog":
        L.append("| %s | %s | %s | (fixed by definition) | n/a | n/a | n/a | n/a |" % (slot, cfgname, f4(mean)))
        continue
    pool = {"C2_best_plain": groups["plain"], "C3_best_hybrid_filter": groups["filter"],
            "C4_best_memory": groups["memory"], "C5_best_dr": groups["DR"] + groups["DRcurr"],
            "C6_best_full": groups["full"]}[slot]
    rivals = [c for c in pool if c != cfgname]
    ru = max(rivals, key=lambda c: t1v[c][0])
    margin = mean - t1v[ru][0]
    ok = "yes" if margin > t1v[ru][1] else "NO(TIE)"
    if sel_prev.get(slot) != cfgname:
        rule_s.append("%s changed %s -> %s" % (slot, sel_prev.get(slot), cfgname))
    if slot == "C2_best_plain" and margin <= t1v[ru][1]:
        rule_s.append("C2 margin %.4f <= runner-up sd %.4f" % (margin, t1v[ru][1]))
    L.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
        slot, cfgname, f4(mean), ru, f4(t1v[ru][0]), f4(margin), f4(t1v[ru][1]), ok))
