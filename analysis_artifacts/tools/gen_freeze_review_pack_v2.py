def fam_of(cfg):
    if "__full" in cfg:
        return "full"
    if "__DRcurr" in cfg:
        return "DRcurr"
    if "__DR" in cfg:
        return "DR"
    if "__filter" in cfg:
        return "filter"
    if re.search(r"__K\d+$|__gru8$", cfg):
        return "memory"
    if "__plain" in cfg:
        return "plain"
    return "?"


groups = {}
for cfg in t1v:
    groups.setdefault(fam_of(cfg), []).append(cfg)
