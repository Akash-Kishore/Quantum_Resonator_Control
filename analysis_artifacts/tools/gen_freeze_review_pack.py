def val_scores(prefix):
    per = {}
    for r in DB:
        m = re.search(r"runs.(.+?).seed_(\d+)$", r["model_dir"] or "")
        if not m:
            continue
        cfg, seed = m.group(1), int(m.group(2))
        if cfg == prefix and r["split"] == "val" and r["cond_id"] in VAL_CONDS:
            per.setdefault(seed, {})[r["cond_id"]] = r["lock_w1000_mean"]
    return per


